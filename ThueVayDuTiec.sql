GO

/* Chuan hoa rang buoc hoan coc cua cac phien ban cu. */
IF OBJECT_ID(N'dbo.CK_TheoDoi_HoanCoc',N'C') IS NOT NULL
    ALTER TABLE dbo.TheoDoiDonThue DROP CONSTRAINT CK_TheoDoi_HoanCoc;
IF OBJECT_ID(N'dbo.RB_TheoDoi_HoanCoc',N'C') IS NOT NULL
    ALTER TABLE dbo.TheoDoiDonThue DROP CONSTRAINT RB_TheoDoi_HoanCoc;
GO
ALTER TABLE dbo.TheoDoiDonThue
    ADD CONSTRAINT CK_TheoDoi_HoanCoc
    CHECK (TienHoanCoc >= 0 AND (TienHoanCoc = 0 OR TienHoanCoc = TienCoc - TienKhauTru));
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name=N'CM_HinhAnhVay_ThuTu' AND object_id=OBJECT_ID(N'dbo.HinhAnhVay'))
    CREATE INDEX CM_HinhAnhVay_ThuTu ON dbo.HinhAnhVay(MaVay,ThuTu);
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name=N'CM_VT_TenCh' AND object_id=OBJECT_ID(N'dbo.VaiTro'))
    CREATE UNIQUE INDEX CM_VT_TenCh ON dbo.VaiTro(TenVTCh) WHERE TenVTCh IS NOT NULL;
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name=N'CM_ND_TenDNCh' AND object_id=OBJECT_ID(N'dbo.NguoiDung'))
    CREATE UNIQUE INDEX CM_ND_TenDNCh ON dbo.NguoiDung(TenDNCh) WHERE TenDNCh IS NOT NULL;
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name=N'CM_ND_ThuDTCh' AND object_id=OBJECT_ID(N'dbo.NguoiDung'))
    CREATE UNIQUE INDEX CM_ND_ThuDTCh ON dbo.NguoiDung(ThuDTCh) WHERE ThuDTCh IS NOT NULL;
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name=N'CM_Don_ND' AND object_id=OBJECT_ID(N'dbo.DonThue'))
    CREATE INDEX CM_Don_ND ON dbo.DonThue(MaND);
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name=N'CM_TBVT_VT' AND object_id=OBJECT_ID(N'dbo.TuyenBoVaiTro'))
    CREATE INDEX CM_TBVT_VT ON dbo.TuyenBoVaiTro(MaVT);
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name=N'CM_TBND_ND' AND object_id=OBJECT_ID(N'dbo.TuyenBoNguoiDung'))
    CREATE INDEX CM_TBND_ND ON dbo.TuyenBoNguoiDung(MaND);
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name=N'CM_DN_ND' AND object_id=OBJECT_ID(N'dbo.DangNhapNgoai'))
    CREATE INDEX CM_DN_ND ON dbo.DangNhapNgoai(MaND);
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name=N'CM_VTND_VT' AND object_id=OBJECT_ID(N'dbo.VaiTroNguoiDung'))
    CREATE INDEX CM_VTND_VT ON dbo.VaiTroNguoiDung(MaVT);
GO

/* Du lieu khoi tao, tranh chen lap khi chay lai. */
IF NOT EXISTS (SELECT 1 FROM dbo.VaiTro WHERE TenVTCh=N'KHACHHANG')
    INSERT dbo.VaiTro(MaVT,TenVT,TenVTCh,MaDB) VALUES(CONVERT(NVARCHAR(50),NEWID()),N'KhachHang',N'KHACHHANG',CONVERT(NVARCHAR(36),NEWID()));
IF NOT EXISTS (SELECT 1 FROM dbo.VaiTro WHERE TenVTCh=N'QUANTRIVIEN')
    INSERT dbo.VaiTro(MaVT,TenVT,TenVTCh,MaDB) VALUES(CONVERT(NVARCHAR(50),NEWID()),N'QuanTriVien',N'QUANTRIVIEN',CONVERT(NVARCHAR(36),NEWID()));
IF NOT EXISTS (SELECT 1 FROM dbo.DanhMucVay WHERE TenDM=N'Váy dạ hội')
    INSERT dbo.DanhMucVay(TenDM,MoTa) VALUES(N'Váy dạ hội',N'Váy dành cho tiệc tối và sự kiện trang trọng.');
IF NOT EXISTS (SELECT 1 FROM dbo.DanhMucVay WHERE TenDM=N'Váy dự tiệc')
    INSERT dbo.DanhMucVay(TenDM,MoTa) VALUES(N'Váy dự tiệc',N'Váy dành cho sinh nhật và các buổi tiệc.');
IF NOT EXISTS (SELECT 1 FROM dbo.DanhMucVay WHERE TenDM=N'Váy nhẹ nhàng')
    INSERT dbo.DanhMucVay(TenDM,MoTa) VALUES(N'Váy nhẹ nhàng',N'Váy phù hợp chụp ảnh và những dịp đặc biệt.');
INSERT dbo.HinhAnhVay(MaVay,DuongDan,AnhChinh,ThuTu)
SELECT v.MaVay,v.HinhAnh,1,0 FROM dbo.VayDuTiec v
WHERE v.HinhAnh IS NOT NULL AND NOT EXISTS
 (SELECT 1 FROM dbo.HinhAnhVay a WHERE a.MaVay=v.MaVay AND a.DuongDan=v.HinhAnh);
GO

