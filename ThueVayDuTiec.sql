USE ThueVayDuTiec;
GO

CREATE TABLE DanhMucVay
(
    MaDM INT IDENTITY(1,1) NOT NULL,
    TenDM NVARCHAR(100) NOT NULL,
    MoTa NVARCHAR(500) NULL,
    CONSTRAINT KC_DM PRIMARY KEY (MaDM)
);
GO

CREATE TABLE VaiTro
(
    MaVT NVARCHAR(50) NOT NULL,
    TenVT NVARCHAR(50) NULL,
    TenVTCh NVARCHAR(50) NULL,
    MaDB NVARCHAR(36) NULL,
    CONSTRAINT KC_VT PRIMARY KEY (MaVT)
);
GO

CREATE TABLE NguoiDung
(
    MaND NVARCHAR(50) NOT NULL,
    HoTen NVARCHAR(100) NOT NULL,
    TenDN NVARCHAR(150) NULL,
    TenDNCh NVARCHAR(150) NULL,
    ThuDT NVARCHAR(150) NULL,
    ThuDTCh NVARCHAR(150) NULL,
    ThuDTXN BIT NOT NULL CONSTRAINT MD_ND_ThuDTXN DEFAULT 0,
    MatKhauBam NVARCHAR(100) NULL,
    MaBM NVARCHAR(36) NULL,
    MaDB NVARCHAR(36) NULL,
    SDT NVARCHAR(30) NULL,
    SDTXN BIT NOT NULL CONSTRAINT MD_ND_SDTXN DEFAULT 0,
    XacThuc2Y BIT NOT NULL CONSTRAINT MD_ND_XT2Y DEFAULT 0,
    KhoaDen DATETIMEOFFSET NULL,
    ChoKhoa BIT NOT NULL CONSTRAINT MD_ND_ChoKhoa DEFAULT 1,
    LanSai INT NOT NULL CONSTRAINT MD_ND_LanSai DEFAULT 0,
    CONSTRAINT KC_ND PRIMARY KEY (MaND)
);
GO

CREATE TABLE VayDuTiec
(
    MaVay INT IDENTITY(1,1) NOT NULL,
    MaDM INT NOT NULL,
    TenVay NVARCHAR(200) NOT NULL,
    KichCo NVARCHAR(30) NOT NULL,
    MauSac NVARCHAR(50) NOT NULL,
    KieuDang NVARCHAR(100) NOT NULL,
    GiaNgay DECIMAL(18,2) NOT NULL,
    TienDatCoc DECIMAL(18,2) NOT NULL,
    HinhAnh NVARCHAR(500) NULL,
    DangKD BIT NOT NULL CONSTRAINT MD_Vay_DangKD DEFAULT 1,
    CONSTRAINT KC_Vay PRIMARY KEY (MaVay),
    CONSTRAINT KN_Vay_DM FOREIGN KEY (MaDM) REFERENCES DanhMucVay(MaDM),
    CONSTRAINT RB_Vay_Gia CHECK (GiaNgay >= 0),
    CONSTRAINT RB_Vay_Coc CHECK (TienDatCoc >= 0)
);
GO

CREATE TABLE HinhAnhVay
(
    MaAnh INT IDENTITY(1,1) NOT NULL,
    MaVay INT NOT NULL,
    DuongDan NVARCHAR(500) NOT NULL,
    AnhChinh BIT NOT NULL CONSTRAINT MD_HinhAnhVay_AnhChinh DEFAULT 0,
    ThuTu INT NOT NULL CONSTRAINT MD_HinhAnhVay_ThuTu DEFAULT 0,
    CONSTRAINT KC_HinhAnhVay PRIMARY KEY (MaAnh),
    CONSTRAINT KN_HinhAnhVay_Vay FOREIGN KEY (MaVay) REFERENCES VayDuTiec(MaVay) ON DELETE CASCADE
);
GO

CREATE INDEX CM_HinhAnhVay_ThuTu ON HinhAnhVay(MaVay, ThuTu);
GO

CREATE TABLE DonThue
(
    MaDon INT IDENTITY(1,1) NOT NULL,
    MaND NVARCHAR(50) NULL,
    HoTen NVARCHAR(100) NOT NULL,
    ThuDT NVARCHAR(150) NOT NULL,
    SDT NVARCHAR(30) NOT NULL,
    NgayTao DATETIME2 NOT NULL CONSTRAINT MD_Don_NgayTao DEFAULT SYSDATETIME(),
    NgayBD DATE NOT NULL,
    NgayKT DATE NOT NULL,
    TongTien DECIMAL(18,2) NOT NULL,
    TrangThai NVARCHAR(30) NOT NULL CONSTRAINT MD_Don_TrangThai DEFAULT N'ChoXacNhan',
    CONSTRAINT KC_Don PRIMARY KEY (MaDon),
    CONSTRAINT KN_Don_ND FOREIGN KEY (MaND) REFERENCES NguoiDung(MaND),
    CONSTRAINT RB_Don_Ngay CHECK (NgayKT >= NgayBD),
    CONSTRAINT RB_Don_Tong CHECK (TongTien >= 0)
);
GO

CREATE TABLE ChiTietDonThue
(
    MaCT INT IDENTITY(1,1) NOT NULL,
    MaDon INT NOT NULL,
    MaVay INT NOT NULL,
    SoNgay INT NOT NULL,
    DonGia DECIMAL(18,2) NOT NULL,
    CONSTRAINT KC_CT PRIMARY KEY (MaCT),
    CONSTRAINT KN_CT_Don FOREIGN KEY (MaDon) REFERENCES DonThue(MaDon),
    CONSTRAINT KN_CT_Vay FOREIGN KEY (MaVay) REFERENCES VayDuTiec(MaVay),
    CONSTRAINT RB_CT_SoNgay CHECK (SoNgay > 0),
    CONSTRAINT RB_CT_Gia CHECK (DonGia >= 0)
);
GO

CREATE TABLE TuyenBoVaiTro
(
    MaTB INT IDENTITY(1,1) NOT NULL,
