SELECT COL_LENGTH(N'dbo.TheoDoiDonThue',N'TienThueDaThu') AS TienThueDaThu,
       COL_LENGTH(N'dbo.TheoDoiDonThue',N'NgayThuTienThue') AS NgayThuTienThue;
