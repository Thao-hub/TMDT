IF OBJECT_ID(N'HinhAnhVay', N'U') IS NULL
BEGIN
    CREATE TABLE HinhAnhVay
    (
        MaAnh INT IDENTITY(1,1) NOT NULL,
        MaVay INT NOT NULL,
        DuongDan NVARCHAR(500) NOT NULL,
        AnhChinh BIT NOT NULL CONSTRAINT MD_HinhAnhVay_AnhChinh DEFAULT 0,
        ThuTu INT NOT NULL CONSTRAINT MD_HinhAnhVay_ThuTu DEFAULT 0,
        CONSTRAINT KC_HinhAnhVay PRIMARY KEY (MaAnh),
        CONSTRAINT KN_HinhAnhVay_Vay
            FOREIGN KEY (MaVay) REFERENCES VayDuTiec(MaVay) ON DELETE CASCADE
    );
END;
GO

IF NOT EXISTS (
    SELECT 1 FROM sys.indexes
    WHERE name = N'CM_HinhAnhVay_ThuTu'
      AND object_id = OBJECT_ID(N'HinhAnhVay')
)
    CREATE INDEX CM_HinhAnhVay_ThuTu ON HinhAnhVay(MaVay, ThuTu);
GO

INSERT INTO HinhAnhVay (MaVay, DuongDan, AnhChinh, ThuTu)
SELECT v.MaVay, v.HinhAnh, 1, 0
FROM VayDuTiec v
WHERE v.HinhAnh IS NOT NULL
  AND NOT EXISTS (
      SELECT 1
      FROM HinhAnhVay a
      WHERE a.MaVay = v.MaVay
        AND a.DuongDan = v.HinhAnh
  );
GO
