USE master;
GO
IF DB_ID(N'ThueVayDuTiec') IS NULL
    CREATE DATABASE [ThueVayDuTiec];
GO
USE [ThueVayDuTiec];
GO

IF OBJECT_ID(N'dbo.DanhMucVay', N'U') IS NULL
CREATE TABLE dbo.DanhMucVay (
    MaDM INT IDENTITY(1,1) NOT NULL CONSTRAINT KC_DM PRIMARY KEY,
    TenDM NVARCHAR(100) NOT NULL,
    MoTa NVARCHAR(500) NULL
);
GO
IF OBJECT_ID(N'dbo.VaiTro', N'U') IS NULL
CREATE TABLE dbo.VaiTro (
    MaVT NVARCHAR(50) NOT NULL CONSTRAINT KC_VT PRIMARY KEY,
    TenVT NVARCHAR(50) NULL,
    TenVTCh NVARCHAR(50) NULL,
    MaDB NVARCHAR(36) NULL
);
GO
IF OBJECT_ID(N'dbo.NguoiDung', N'U') IS NULL
CREATE TABLE dbo.NguoiDung (
    MaND NVARCHAR(50) NOT NULL CONSTRAINT KC_ND PRIMARY KEY,
    HoTen NVARCHAR(100) NOT NULL,
    TenDN NVARCHAR(150) NULL, TenDNCh NVARCHAR(150) NULL,
    ThuDT NVARCHAR(150) NULL, ThuDTCh NVARCHAR(150) NULL,
    ThuDTXN BIT NOT NULL CONSTRAINT MD_ND_ThuDTXN DEFAULT 0,
    MatKhauBam NVARCHAR(100) NULL, MaBM NVARCHAR(36) NULL, MaDB NVARCHAR(36) NULL,
    SDT NVARCHAR(30) NULL,
    SDTXN BIT NOT NULL CONSTRAINT MD_ND_SDTXN DEFAULT 0,
    XacThuc2Y BIT NOT NULL CONSTRAINT MD_ND_XT2Y DEFAULT 0,
    KhoaDen DATETIMEOFFSET NULL,
    ChoKhoa BIT NOT NULL CONSTRAINT MD_ND_ChoKhoa DEFAULT 1,
    LanSai INT NOT NULL CONSTRAINT MD_ND_LanSai DEFAULT 0
);
GO
IF OBJECT_ID(N'dbo.VayDuTiec', N'U') IS NULL
CREATE TABLE dbo.VayDuTiec (
    MaVay INT IDENTITY(1,1) NOT NULL CONSTRAINT KC_Vay PRIMARY KEY,
    MaDM INT NOT NULL,
    TenVay NVARCHAR(200) NOT NULL,
    KichCo NVARCHAR(30) NOT NULL,
    MauSac NVARCHAR(50) NOT NULL,
    KieuDang NVARCHAR(100) NOT NULL,
    GiaNgay DECIMAL(18,2) NOT NULL,
    TienDatCoc DECIMAL(18,2) NOT NULL,
    HinhAnh NVARCHAR(500) NULL,
    DangKD BIT NOT NULL CONSTRAINT MD_Vay_DangKD DEFAULT 1,
    CONSTRAINT KN_Vay_DM FOREIGN KEY (MaDM) REFERENCES dbo.DanhMucVay(MaDM),
    CONSTRAINT RB_Vay_Gia CHECK (GiaNgay >= 0),
    CONSTRAINT RB_Vay_Coc CHECK (TienDatCoc >= 0)
);
GO
IF OBJECT_ID(N'dbo.HinhAnhVay', N'U') IS NULL
CREATE TABLE dbo.HinhAnhVay (
    MaAnh INT IDENTITY(1,1) NOT NULL CONSTRAINT KC_HinhAnhVay PRIMARY KEY,
    MaVay INT NOT NULL,
    DuongDan NVARCHAR(500) NOT NULL,
    AnhChinh BIT NOT NULL CONSTRAINT MD_HinhAnhVay_AnhChinh DEFAULT 0,
    ThuTu INT NOT NULL CONSTRAINT MD_HinhAnhVay_ThuTu DEFAULT 0,
    CONSTRAINT KN_HinhAnhVay_Vay FOREIGN KEY (MaVay) REFERENCES dbo.VayDuTiec(MaVay) ON DELETE CASCADE
);
GO
IF OBJECT_ID(N'dbo.DonThue', N'U') IS NULL
CREATE TABLE dbo.DonThue (
    MaDon INT IDENTITY(1,1) NOT NULL CONSTRAINT KC_Don PRIMARY KEY,
    MaND NVARCHAR(50) NULL,
    HoTen NVARCHAR(100) NOT NULL,
    ThuDT NVARCHAR(150) NOT NULL,
    SDT NVARCHAR(30) NOT NULL,
    NgayTao DATETIME2 NOT NULL CONSTRAINT MD_Don_NgayTao DEFAULT SYSDATETIME(),
    NgayBD DATE NOT NULL, NgayKT DATE NOT NULL,
    TongTien DECIMAL(18,2) NOT NULL,
    TrangThai NVARCHAR(30) NOT NULL CONSTRAINT MD_Don_TrangThai DEFAULT N'ChoXacNhan',
    LyDoHuy NVARCHAR(500) NULL,
    CONSTRAINT KN_Don_ND FOREIGN KEY (MaND) REFERENCES dbo.NguoiDung(MaND),
    CONSTRAINT RB_Don_Ngay CHECK (NgayKT >= NgayBD),
    CONSTRAINT RB_Don_Tong CHECK (TongTien >= 0)
);
GO
IF OBJECT_ID(N'dbo.TheoDoiDonThue', N'U') IS NULL
CREATE TABLE dbo.TheoDoiDonThue (
    MaDon INT NOT NULL CONSTRAINT KC_TheoDoiDonThue PRIMARY KEY,
    NgayNhan DATETIME2 NULL, NgayKhongDenNhan DATETIME2 NULL,
    GhiChuKhongDenNhan NVARCHAR(500) NULL,
    TienCocMat DECIMAL(18,2) NOT NULL CONSTRAINT MD_TheoDoi_TienCocMat DEFAULT 0,
    NgayKiemTra DATETIME2 NULL, TinhTrang NVARCHAR(30) NULL, GhiChu NVARCHAR(1000) NULL,
    TienCoc DECIMAL(18,2) NOT NULL CONSTRAINT MD_TheoDoi_TienCoc DEFAULT 0,
    TienThueDaThu DECIMAL(18,2) NOT NULL CONSTRAINT MD_TheoDoi_TienThueDaThu DEFAULT 0,
    NgayThuTienThue DATETIME2 NULL,
    TienKhauTru DECIMAL(18,2) NOT NULL CONSTRAINT MD_TheoDoi_KhauTru DEFAULT 0,
    TienHoanCoc DECIMAL(18,2) NOT NULL CONSTRAINT MD_TheoDoi_HoanCoc DEFAULT 0,
    HinhThucHoanCoc NVARCHAR(30) NULL, NgayHoanCoc DATETIME2 NULL,
    MaNDThucHien NVARCHAR(50) NULL,
    CONSTRAINT KN_TheoDoi_Don FOREIGN KEY (MaDon) REFERENCES dbo.DonThue(MaDon) ON DELETE CASCADE,
    CONSTRAINT RB_TheoDoi_TienCoc CHECK (TienCoc >= 0),
    CONSTRAINT RB_TheoDoi_KhauTru CHECK (TienKhauTru >= 0 AND TienKhauTru <= TienCoc),
    CONSTRAINT RB_TheoDoi_HoanCoc CHECK (TienHoanCoc >= 0 AND (TienHoanCoc = 0 OR TienHoanCoc = TienCoc - TienKhauTru)),
    CONSTRAINT RB_TheoDoi_TienCocMat CHECK (TienCocMat >= 0),
    CONSTRAINT RB_TheoDoi_TienThueDaThu CHECK (TienThueDaThu >= 0)
);
GO
IF OBJECT_ID(N'dbo.ChiTietDonThue', N'U') IS NULL
CREATE TABLE dbo.ChiTietDonThue (
    MaCT INT IDENTITY(1,1) NOT NULL CONSTRAINT KC_CT PRIMARY KEY,
    MaDon INT NOT NULL, MaVay INT NOT NULL, SoNgay INT NOT NULL, DonGia DECIMAL(18,2) NOT NULL,
    CONSTRAINT KN_CT_Don FOREIGN KEY (MaDon) REFERENCES dbo.DonThue(MaDon),
    CONSTRAINT KN_CT_Vay FOREIGN KEY (MaVay) REFERENCES dbo.VayDuTiec(MaVay),
    CONSTRAINT RB_CT_SoNgay CHECK (SoNgay > 0),
    CONSTRAINT RB_CT_Gia CHECK (DonGia >= 0)
);
GO
IF OBJECT_ID(N'dbo.TuyenBoVaiTro', N'U') IS NULL
CREATE TABLE dbo.TuyenBoVaiTro (
    MaTB INT IDENTITY(1,1) NOT NULL CONSTRAINT KC_TBVT PRIMARY KEY,
    MaVT NVARCHAR(50) NOT NULL, LoaiTB NVARCHAR(256) NULL, GTTB NVARCHAR(1000) NULL,
    CONSTRAINT KN_TBVT_VT FOREIGN KEY (MaVT) REFERENCES dbo.VaiTro(MaVT) ON DELETE CASCADE
);
GO
IF OBJECT_ID(N'dbo.TuyenBoNguoiDung', N'U') IS NULL
CREATE TABLE dbo.TuyenBoNguoiDung (
    MaTB INT IDENTITY(1,1) NOT NULL CONSTRAINT KC_TBND PRIMARY KEY,
    MaND NVARCHAR(50) NOT NULL, LoaiTB NVARCHAR(256) NULL, GTTB NVARCHAR(1000) NULL,
    CONSTRAINT KN_TBND_ND FOREIGN KEY (MaND) REFERENCES dbo.NguoiDung(MaND) ON DELETE CASCADE
);
GO
IF OBJECT_ID(N'dbo.DangNhapNgoai', N'U') IS NULL
CREATE TABLE dbo.DangNhapNgoai (
    NhaCC NVARCHAR(128) NOT NULL, KhoaNCC NVARCHAR(128) NOT NULL,
    TenHienThiNCC NVARCHAR(100) NULL, MaND NVARCHAR(50) NOT NULL,
    CONSTRAINT KC_DN PRIMARY KEY (NhaCC,KhoaNCC),
    CONSTRAINT KN_DN_ND FOREIGN KEY (MaND) REFERENCES dbo.NguoiDung(MaND) ON DELETE CASCADE
);
GO
IF OBJECT_ID(N'dbo.VaiTroNguoiDung', N'U') IS NULL
CREATE TABLE dbo.VaiTroNguoiDung (
    MaND NVARCHAR(50) NOT NULL, MaVT NVARCHAR(50) NOT NULL,
    CONSTRAINT KC_VTND PRIMARY KEY (MaND,MaVT),
    CONSTRAINT KN_VTND_ND FOREIGN KEY (MaND) REFERENCES dbo.NguoiDung(MaND) ON DELETE CASCADE,
    CONSTRAINT KN_VTND_VT FOREIGN KEY (MaVT) REFERENCES dbo.VaiTro(MaVT) ON DELETE CASCADE
);
GO
IF OBJECT_ID(N'dbo.MaTruyCapNguoiDung', N'U') IS NULL
CREATE TABLE dbo.MaTruyCapNguoiDung (
    MaND NVARCHAR(50) NOT NULL, NhaCC NVARCHAR(128) NOT NULL, TenMa NVARCHAR(128) NOT NULL,
    GTMa NVARCHAR(1000) NULL,
    CONSTRAINT KC_MaTC PRIMARY KEY (MaND,NhaCC,TenMa),
    CONSTRAINT KN_MaTC_ND FOREIGN KEY (MaND) REFERENCES dbo.NguoiDung(MaND) ON DELETE CASCADE
);
GO

